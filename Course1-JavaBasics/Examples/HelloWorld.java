/**
 * HelloWorld.java
 * Your first Java program!
 * This program demonstrates the basic structure of a Java application.
 */

public class HelloWorld {
    public static void main(String[] args) {
        // Print a welcome message
        System.out.println("Hello, World!");
        System.out.println("Welcome to Java programming!");
        System.out.println("This is your first step into the world of Java.");
        
        // Print a blank line
        System.out.println();
        
        // Print without a new line
        System.out.print("Java ");
        System.out.print("is ");
        System.out.print("awesome!");
        System.out.println(); // Add a new line at the end
    }
}
